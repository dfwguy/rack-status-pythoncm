/**
 * The SRP client must agree with the server, byte for byte.
 *
 * **This is the only test that matters here.** A parameter mismatch between the two halves — group,
 * hash, or RFC 5054 padding — does not raise anywhere: it produces a proof the server rejects, so
 * every login in production looks exactly like a wrong password. No amount of unit-testing the
 * helpers in isolation would catch it.
 *
 * So the fixture is not hand-written. `__fixtures__/srp-vector.json` was generated by running a
 * real exchange against `backend/identity/srp.py`, capturing the client's private value along with
 * the salt and `B` the server produced and the `M`/`HAMK` that verified. Replaying it with the same
 * private value must reproduce the same proof. Regenerate it from the server if the server's
 * parameters ever change — never by copying what this implementation happens to output, which would
 * turn the test into a mirror.
 */

import { afterEach, describe, expect, it } from "vitest";

import vector from "./__fixtures__/srp-vector.json";
import { srpLogin, startSrp } from "./srpClient";

describe("interoperability with the server's SRP implementation", () => {
  it("reproduces the proof the server accepted", async () => {
    const handshake = startSrp(vector.login, vector.password, BigInt("0x" + vector.a_hex));

    expect(handshake.A).toBe(vector.A_hex);

    const proof = await handshake.proof(vector.salt_hex, vector.B_hex);
    expect(proof).toBe(vector.expected_M_hex);
  });

  it("accepts the server's own proof", async () => {
    const handshake = startSrp(vector.login, vector.password, BigInt("0x" + vector.a_hex));
    await handshake.proof(vector.salt_hex, vector.B_hex);

    expect(handshake.verifyServer(vector.expected_HAMK_hex)).toBe(true);
  });

  it("rejects a server proof that is merely close", async () => {
    const handshake = startSrp(vector.login, vector.password, BigInt("0x" + vector.a_hex));
    await handshake.proof(vector.salt_hex, vector.B_hex);

    const tampered = vector.expected_HAMK_hex.slice(0, -2) + (
      vector.expected_HAMK_hex.endsWith("00") ? "01" : "00"
    );
    expect(handshake.verifyServer(tampered)).toBe(false);
  });

  it("produces a different proof for a wrong password", async () => {
    const handshake = startSrp(vector.login, "not-the-password", BigInt("0x" + vector.a_hex));
    const proof = await handshake.proof(vector.salt_hex, vector.B_hex);

    expect(proof).not.toBe(vector.expected_M_hex);
  });

  it("uses the 4096-bit group with g=5, as the server does", () => {
    expect(BigInt("0x" + vector.N_hex).toString(2).length).toBe(4096);
    expect(vector.g).toBe(5);
    expect(vector.rfc5054_padding).toBe(true);
  });
});

describe("the handshake refuses what the protocol says to refuse", () => {
  it("rejects B ≡ 0 (mod N)", async () => {
    const handshake = startSrp("someone", "password");
    // N itself is ≡ 0, and would force the session key to a constant.
    await expect(handshake.proof(vector.salt_hex, vector.N_hex)).rejects.toThrow(/invalid B/);
  });

  it("will not verify a server proof before one has been computed", () => {
    const handshake = startSrp("someone", "password");
    expect(handshake.verifyServer(vector.expected_HAMK_hex)).toBe(false);
  });

  it("uses a fresh private value per exchange", () => {
    const first = startSrp("someone", "password");
    const second = startSrp("someone", "password");
    expect(first.A).not.toBe(second.A);
  });
});

describe("srpLogin does not become the oracle the API refuses to be", () => {
  const originalFetch = globalThis.fetch;

  afterEach(() => {
    globalThis.fetch = originalFetch;
  });

  it("reports the same message for an unknown login and a wrong password", async () => {
    globalThis.fetch = (async () =>
      new Response(JSON.stringify({ ok: false, error: "authentication failed" }), {
        status: 401,
        headers: { "Content-Type": "application/json" },
      })) as typeof fetch;

    const unknown = await srpLogin("no-such-person", "x");
    const wrong = await srpLogin("admin", "wrong");

    expect(unknown.ok).toBe(false);
    expect(unknown.error).toBe(wrong.error);
  });

  it("surfaces a rate limit as something the user can act on", async () => {
    globalThis.fetch = (async () =>
      new Response("{}", { status: 429, headers: { "Retry-After": "42" } })) as typeof fetch;

    const result = await srpLogin("admin", "x");
    expect(result.ok).toBe(false);
    expect(result.error).toMatch(/42 seconds/);
  });

  it("refuses a session when the server cannot prove itself", async () => {
    // A server that answers the exchange but returns a bogus HAMK is an impostor; establishing a
    // session with it is exactly what mutual authentication exists to prevent.
    globalThis.fetch = (async (url: string | URL | Request) => {
      const href = String(url);
      if (href.endsWith("/begin")) {
        return new Response(
          JSON.stringify({ ok: true, token: "t", salt: vector.salt_hex, B: vector.B_hex }),
          { status: 200, headers: { "Content-Type": "application/json" } },
        );
      }
      return new Response(
        JSON.stringify({ ok: true, HAMK: "00".repeat(32), user: { login: "admin" } }),
        { status: 200, headers: { "Content-Type": "application/json" } },
      );
    }) as typeof fetch;

    const result = await srpLogin(vector.login, vector.password);
    expect(result.ok).toBe(false);
    expect(result.error).toMatch(/failed to authenticate itself/);
  });

  it("does not report success when the network is unreachable", async () => {
    globalThis.fetch = (async () => {
      throw new TypeError("network down");
    }) as typeof fetch;

    const result = await srpLogin("admin", "x");
    expect(result.ok).toBe(false);
    expect(result.error).toMatch(/reach the server/);
  });
});
