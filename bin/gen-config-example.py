"""Render `config/rackstatus.toml.example` from the settings registry (DC-5, FR-1b, FR-1e).

Generated, not hand-written, so the example cannot drift from the code that reads it. A hand-kept
example is the same problem as a hand-kept test citation: it is correct on the day it is written and
silently wrong from the first setting anyone adds.

    bin/gen-config-example.py           # write the file
    bin/gen-config-example.py --check   # CI: fail if the tracked file is stale

`--check` exists because the useful failure is not "the example is wrong" but "somebody added a
setting and did not regenerate", and that is only visible by comparing.

**Every line is commented out.** A copied file must be inert: `cp rackstatus.toml.example
rackstatus.toml` on a live deployment has to change nothing until the operator deliberately
uncomments something. An example whose act of copying reconfigures a cluster is a trap.
"""

from __future__ import annotations

import argparse
import sys
import textwrap
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
OUTPUT = REPO_ROOT / "config" / "rackstatus.toml.example"
WIDTH = 96

PREAMBLE = """\
NVIS Rack Status — launch configuration (EXAMPLE: every setting this file can carry)

GENERATED by bin/gen-config-example.py from backend/config_registry.py. Do not hand-edit:
add or change the declaration and regenerate, or the example drifts from the code that reads
it.

Start from the minimal file instead: `python backend/cli.py init-config --ssh-host <head>`
writes `config/rackstatus.toml` with only what a deployment needs. Copy lines from here into
it as you need them — every line below is commented out, so nothing here takes effect by
itself. Point elsewhere with NVIS_RACKSTATUS_CONFIG=/path/to/file.

PRECEDENCE — this file is the baseline. A real environment variable, or a `docker run -e`
flag, overrides anything here. So a site can keep a checked-in-shape file and still override
one setting for a single run.

TABLES GROUP, THEY DO NOT NAMESPACE. A leaf key is the exact environment variable name:
`[auth] RACK_WEB_OIDC_ISSUER = "..."` sets RACK_WEB_OIDC_ISSUER, not
AUTH_RACK_WEB_OIDC_ISSUER. The same key in two tables is refused, since file order would
otherwise decide its value.

NO SECRETS. A setting resolved as secret makes startup fail if it appears here — this file
is exactly the artifact that ends up in bug reports and support bundles, and a copy of it
does not inherit .gitignore. Put secrets in the environment or a mounted secret.

FLOATS ARE REFUSED. Quote version-like values: `"13.3"`, not `13.3`. Rendering a float
changes it (13.30 becomes 13.3), and the settings shaped that way here are version strings
compared as strings.

NOT CONFIGURABLE HERE: RACK_WEB_BIND_ADDR, RACK_WEB_PORT, RACK_SSH_KEY_PATH,
RACK_WEB_TLS_CERT, RACK_WEB_TLS_KEY and NVIS_RACKSTATUS_CONFIG. docker-compose.yml
interpolates the first three to publish the port and mount the SSH key, which Docker
resolves before Python starts — keep them in `.env`. The certificate is settled before this
file is read: put yours in `config/tls/` (or set the two variables in the environment). The
last cannot name the path to itself.\
"""


def _comment(text: str, width: int = WIDTH) -> list[str]:
    """Wrap on word boundaries.

    The first version of this chunked on a fixed character count and split words down the middle
    ("der" / "ive from it"), which is the kind of detail that makes a generated file look
    untrustworthy even when its content is right.
    """
    out: list[str] = []
    for paragraph in text.split("\n"):
        if not paragraph.strip():
            out.append("#")
            continue
        out += [f"# {line}" for line in textwrap.wrap(paragraph, width=width - 2)]
    return out


def render() -> str:
    sys.path.insert(0, str(REPO_ROOT / "backend"))
    import config_registry

    lines = _comment(PREAMBLE) + [""]

    by_section: dict[str, list] = {}
    for setting in config_registry.declared().values():
        by_section.setdefault(setting.section, []).append(setting)

    # Sections ordered so the ones an operator edits first come first, then alphabetically for
    # anything a later declaration introduces.
    preferred = ["general", "connection", "cluster", "auth", "tls", "validation", "nvftp"]
    ordered = [s for s in preferred if s in by_section] + sorted(
        set(by_section) - set(preferred)
    )

    for section in ordered:
        lines.append(f"[{section}]")
        for setting in sorted(by_section[section], key=lambda s: s.name):
            lines += _comment(setting.description)
            if setting.required_when is not None:
                lines += _comment(
                    "REQUIRED under the condition above — startup refuses, naming this setting, "
                    "rather than failing later."
                )
            if setting.is_secret:
                # Belt and braces: a secret should not reach this file at all, and if a future
                # declaration marks one, the example must not invite anyone to set it here.
                lines += _comment("SECRET — must NOT be set in this file; use the environment.")
                lines.append(f"# {setting.name} = <set in the environment, not here>")
            else:
                value = _literal(setting)
                lines.append(f"# {setting.name} = {value}")
            lines.append("")
        lines.append("")

    return "\n".join(lines).rstrip("\n") + "\n"


def _literal(setting) -> str:
    """The example value as valid TOML for its declared type.

    Rendering a bool as `"false"` would be a string, and an int as `"22"` likewise — an operator
    uncommenting it would then get a type the loader refuses, from a file that is supposed to be
    the worked example.
    """
    import config_registry

    raw = setting.example
    if not raw:
        return "..."
    if setting.toml_type == config_registry.TOML_BOOL:
        return raw.strip().lower()
    if setting.toml_type == config_registry.TOML_INT:
        return raw.strip()
    if setting.toml_type == config_registry.TOML_ARRAY:
        return "[" + ", ".join(f'"{p.strip()}"' for p in raw.split(",")) + "]"
    return f'"{raw}"'


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero if the tracked file differs from what the registry would produce",
    )
    args = parser.parse_args()

    rendered = render()
    if args.check:
        current = OUTPUT.read_text() if OUTPUT.exists() else ""
        if current != rendered:
            print(
                f"{OUTPUT.relative_to(REPO_ROOT)} is stale — a setting was added or changed "
                f"without regenerating.\nRun: bin/gen-config-example.py",
                file=sys.stderr,
            )
            return 1
        print(f"{OUTPUT.relative_to(REPO_ROOT)} is current")
        return 0

    OUTPUT.write_text(rendered)
    print(f"wrote {OUTPUT.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
