"""Materialise the action vocabulary as a document — the source of truth for services and actions.

**Why this exists.** The vocabulary was real but unpublished: it lived as
`backend/tests/action_snapshot.json`, framed as a regression snapshot, regenerated by a shell
heredoc pasted out of a docstring. So anything that needed to *know* the services and actions —
a policy preview, a test, an operator writing a policy — either called the live registry or guessed.
Guessing is what happened: a test asserting `rack:read` passed review and failed, because the real
action is `rack:list`.

The registry stays the runtime authority. This writes it down, so a reader, a test and a document
can agree without starting the application.

Two outputs, one dataset:

* ``docs/action-vocabulary.json`` — machine-readable, grouped by service, with the resource type
  and whether each action reads or mutates.
* ``docs/ACTION_VOCABULARY.md`` — the same content as a table, because an operator choosing
  actions for a policy reads prose and the JSON is unreadable at 254 rows.

Usage::

    bin/gen-action-vocabulary.py           # write both
    bin/gen-action-vocabulary.py --check   # exit non-zero if either is stale (CI gate)
"""

from __future__ import annotations

import argparse
import ast
import difflib
import json
import os
import pathlib
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
JSON_OUT = REPO_ROOT / "docs" / "action-vocabulary.json"
MD_OUT = REPO_ROOT / "docs" / "ACTION_VOCABULARY.md"
#: The same content as a page *inside* the documentation site.
#:
#: A third output rather than a move, which `docs/README.md` asks for explicitly: the flat file is
#: a CI-gated artifact that eleven places reference, while this is a rendering of it. The site
#: excludes `[A-Z]*.md` by design, so the list existed for months and was not in `_toc.yml` --
#: a reader looking for "which services and actions are there" found the grammar page and never
#: the vocabulary. Both files come from one `render_markdown`, so they cannot disagree.
SITE_OUT = REPO_ROOT / "docs" / "reference" / "identity" / "action-vocabulary.md"


def _load_registry():
    """Import the app and hand back its live registry.

    Demo mode and a file log sink, because importing `app` otherwise reaches for a cluster and
    writes to wherever the deployment's logging is pointed — neither of which a generator should do.
    """
    sys.path.insert(0, str(REPO_ROOT / "backend"))
    os.environ.setdefault("RACK_STATUS_DEMO", "1")
    os.environ.setdefault("NVIS_LOG_SINKS", "file")
    os.environ.setdefault("NVIS_LOG_FILE", "/tmp/gen-action-vocabulary.log")

    import app  # noqa: F401  (imported for its side effect: the registry is built at import)
    from audit import actions as audit_actions

    return audit_actions


def _owning_module(routes: list[str]) -> str:
    """The `api/` module behind a service's routes, from the blueprint prefix of an endpoint.

    Endpoints read `blueprint.view`, and `backend/api/<blueprint>.py` is where the loader found
    it, so this is a lookup rather than a guess. A service whose routes span two blueprints
    resolves to the first with a docstring, which is the one that named the action.
    """
    for route in routes:
        endpoint = route.split()[-1]
        if "." not in endpoint:
            continue
        module = endpoint.split(".", 1)[0]
        candidate = REPO_ROOT / "backend" / "api" / f"{module}.py"
        if candidate.is_file():
            return str(candidate)
    return ""


def _module_summary(path: str) -> str:
    """The first line of a module's docstring.

    **Descriptions are read from the code rather than written here**, which is the only way 53 of
    them stay true: the docstring is already written, already reviewed, and changes in the same
    commit as the behaviour it describes. A hand-kept list beside the generated one is the drift
    this whole file exists to prevent.
    """
    if not path:
        return ""
    try:
        tree = ast.parse(pathlib.Path(path).read_text(errors="replace"))
    except (OSError, SyntaxError):
        return ""
    doc = (ast.get_docstring(tree) or "").strip()
    if not doc:
        return ""
    first = doc.split("\n", 1)[0].strip()
    # Drop a trailing colon: several docstrings open with "X: the endpoints only." and the colon
    # reads as a broken sentence in a table cell.
    return first.rstrip(":")


def _resource_attributes(resource_type: str, resources) -> dict:
    """How a policy names *one* of these, which is what `resources` in a policy needs.

    Everything here is read from `authz/resources.py` rather than described: the keys a request
    is searched for, whether the identifier is case-folded (the difference between
    `deny rack.power:p17-r01` working and silently not), and whether an unnamed target falls
    back to the collection.
    """
    extractor = resources._RESOLVERS.get(resource_type)
    keys = list(getattr(extractor, "keys", ()) or ())
    folded = resource_type in getattr(resources, "_FOLDED_TYPES", frozenset())
    return {
        "identified_by": keys,
        "case_folded": folded,
        "collection_fallback_verbs": sorted(resources.COLLECTION_FALLBACK_VERBS),
    }


def build() -> dict:
    """The dataset. Grouped by service, because that is how an operator scopes a policy."""
    audit_actions = _load_registry()
    registry = audit_actions.registry()

    import authz.resources as resources

    read_verbs = {"read", "list"}
    services: dict[str, dict] = {}

    for action_name, entries in sorted(registry.by_action().items()):
        service, _, verb = action_name.partition(":")
        resource_type = action_name.split(":", 1)[0]
        services.setdefault(service, {"service": service, "actions": []})
        services[service]["actions"].append({
            "action": action_name,
            "verb": verb,
            "kind": "read" if verb in read_verbs else "mutate",
            # Whether a policy can name one instance or only the type. An operator writing
            # `resources` needs to know which of the two they are dealing with.
            "scope": "singleton" if resources.is_singleton(resource_type) else "instance",
            "routes": sorted(
                {f"{entry.method} {entry.endpoint}" for entry in entries}
            ),
        })

    # Per-service prose and resource attributes, both derived. See `_module_summary` for why the
    # description is read out of the owning module rather than maintained here.
    for service in services.values():
        all_routes = [r for a in service["actions"] for r in a["routes"]]
        module = _owning_module(all_routes)
        service["module"] = module.replace(str(REPO_ROOT) + "/", "") if module else ""
        service["summary"] = _module_summary(module)
        service["scope"] = (
            "singleton" if resources.is_singleton(service["service"]) else "instance"
        )
        service["resource"] = _resource_attributes(service["service"], resources)

    actions = [a for s in services.values() for a in s["actions"]]
    return {
        "_comment": (
            "GENERATED by bin/gen-action-vocabulary.py from the live action registry. Do not edit. "
            "This is the source of truth for services and actions: a policy author, a test and the "
            "policy editor all read it instead of guessing action names."
        ),
        "counts": {
            "services": len(services),
            "actions": len(actions),
            "reads": sum(1 for a in actions if a["kind"] == "read"),
            "mutations": sum(1 for a in actions if a["kind"] == "mutate"),
        },
        "resource_types": sorted(resources.declared_types()),
        "services": [services[name] for name in sorted(services)],
    }


def render_markdown(data: dict) -> str:
    counts = data["counts"]
    lines = [
        "<!-- GENERATED by bin/gen-action-vocabulary.py. Do not edit. -->",
        "",
        "# Action vocabulary",
        "",
        "Every action the product declares, which is what a policy's `actions` field may name.",
        "**Generated from the live registry** — a route without a declaration cannot appear here,",
        "and the build gate in `backend/tests/test_action_coverage.py` fails if one exists.",
        "",
        f"{counts['actions']} actions across {counts['services']} services: "
        f"{counts['reads']} reads and {counts['mutations']} mutations.",
        "",
        "A read-only role is `[\"*:read\", \"*:list\"]` — the two read verbs — rather than an",
        "enumeration of the reads below.",
        "",
        "Each service's description is the first line of the module that owns it, so it is written",
        "and reviewed in the same commit as the behaviour. `Identified by` is the request keys a",
        "policy's target is read from; `case-folded` matters because a `deny` written in the other",
        "case does not match.",
        "",
        "## Services at a glance",
        "",
        "| Service | Scope | Actions | What it governs |",
        "|---|---|---|---|",
    ]
    for service in data["services"]:
        summary = service.get("summary") or "—"
        lines.append(
            f"| [`{service['service']}`](#{_anchor(service['service'])}) "
            f"| {service.get('scope', '')} | {len(service['actions'])} | {summary} |"
        )
    lines.append("")

    for service in data["services"]:
        res = service.get("resource") or {}
        keys = res.get("identified_by") or []
        lines += [
            f"## `{service['service']}`",
            "",
        ]
        if service.get("summary"):
            lines += [service["summary"], ""]
        if service.get("module"):
            lines += [f"Owned by `{service['module']}`.", ""]
        if service.get("scope") == "singleton":
            lines += [
                "**One instance per deployment.** A policy names it as "
                f"`{service['service']}:default`; there is no id to narrow a grant to.",
                "",
            ]
        elif keys:
            folded = " The identifier is **case-folded**, so a `deny` must be written in lower case." if res.get("case_folded") else ""
            lines += [
                "Identified by " + ", ".join(f"`{k}`" for k in keys) + " on the request."
                + folded,
                "",
            ]
        lines += [
            "| Action | Kind | Scope | Routes |",
            "|---|---|---|---|",
        ]
        for entry in service["actions"]:
            routes = "<br>".join(f"`{r}`" for r in entry["routes"])
            lines.append(
                f"| `{entry['action']}` | {entry['kind']} | {entry['scope']} | {routes} |"
            )
        lines.append("")
    return "\n".join(lines) + "\n"


SITE_FRONTMATTER = "\n".join([
    "---",
    "diataxis: reference",
    "description: Every service, what it governs, its actions, and how a policy names one instance.",
    "---",
    "",
])


def render_site_page(data: dict) -> str:
    """The same markdown, with the frontmatter the site's structure gate requires."""
    return SITE_FRONTMATTER + render_markdown(data)


def _anchor(service: str) -> str:
    """The in-page anchor Sphinx gives a service heading."""
    return service.replace(".", "").replace("_", "-")


def render_json(data: dict) -> str:
    return json.dumps(data, indent=2, sort_keys=False) + "\n"


def _diff(path: Path, generated: str) -> str:
    """A unified diff of the tracked file against what the registry now produces.

    `--check` used to report only *which* files were stale, so the CI gate shelled out to
    `git diff` to show the contributor which action had changed. That cost the job a `git` binary
    — which `python:3.12-slim` does not have — so it failed with `git: command not found` and then
    reported "a generated source of truth is stale", blaming the documents for a missing tool.
    Printing the diff here keeps what git was there for and needs nothing but the stdlib.
    """
    tracked = path.read_text(encoding="utf-8").splitlines() if path.exists() else []
    name = str(path.relative_to(REPO_ROOT))
    return "\n".join(difflib.unified_diff(
        tracked,
        generated.splitlines(),
        fromfile=f"{name} (tracked)",
        tofile=f"{name} (regenerated)",
        lineterm="",
    ))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero if either tracked file differs from what the registry would produce",
    )
    args = parser.parse_args()

    data = build()
    rendered = {
        JSON_OUT: render_json(data),
        MD_OUT: render_markdown(data),
        SITE_OUT: render_site_page(data),
    }

    if args.check:
        stale = [
            path for path, text in rendered.items()
            if not path.exists() or path.read_text(encoding="utf-8") != text
        ]
        if stale:
            for path in stale:
                print(_diff(path, rendered[path]), file=sys.stderr)
            print(
                "stale: "
                + ", ".join(str(p.relative_to(REPO_ROOT)) for p in stale)
                + "\nAn action was added, removed or renamed without regenerating."
                + "\nRun: bin/gen-action-vocabulary.py",
                file=sys.stderr,
            )
            return 1
        print("action vocabulary is current")
        return 0

    for path, text in rendered.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
