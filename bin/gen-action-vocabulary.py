"""Materialise the action vocabulary as a document — the source of truth for services and actions.

**Why this exists.** The vocabulary was real but unpublished: it lived as
`backend/tests/action_snapshot.json`, framed as a regression snapshot, regenerated by a shell
heredoc pasted out of a docstring. So anything that needed to *know* the services and actions —
a policy preview, a test, an operator writing a policy — either called the live registry or guessed.
Guessing is what happened: a test asserting `rack:read` passed review and failed, because the real
action is `rack:list`.

The registry stays the runtime authority. This writes it down, so a reader, a test and a document
can agree without starting the application.

Two outputs, one dataset:

* ``docs/action-vocabulary.json`` — machine-readable, grouped by service, with the resource type
  and whether each action reads or mutates.
* ``docs/ACTION_VOCABULARY.md`` — the same content as a table, because an operator choosing
  actions for a policy reads prose and the JSON is unreadable at 254 rows.

Usage::

    bin/gen-action-vocabulary.py           # write both
    bin/gen-action-vocabulary.py --check   # exit non-zero if either is stale (CI gate)
"""

from __future__ import annotations

import argparse
import difflib
import json
import os
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
JSON_OUT = REPO_ROOT / "docs" / "action-vocabulary.json"
MD_OUT = REPO_ROOT / "docs" / "ACTION_VOCABULARY.md"


def _load_registry():
    """Import the app and hand back its live registry.

    Demo mode and a file log sink, because importing `app` otherwise reaches for a cluster and
    writes to wherever the deployment's logging is pointed — neither of which a generator should do.
    """
    sys.path.insert(0, str(REPO_ROOT / "backend"))
    os.environ.setdefault("RACK_STATUS_DEMO", "1")
    os.environ.setdefault("NVIS_LOG_SINKS", "file")
    os.environ.setdefault("NVIS_LOG_FILE", "/tmp/gen-action-vocabulary.log")

    import app  # noqa: F401  (imported for its side effect: the registry is built at import)
    from audit import actions as audit_actions

    return audit_actions


def build() -> dict:
    """The dataset. Grouped by service, because that is how an operator scopes a policy."""
    audit_actions = _load_registry()
    registry = audit_actions.registry()

    import authz.resources as resources

    read_verbs = {"read", "list"}
    services: dict[str, dict] = {}

    for action_name, entries in sorted(registry.by_action().items()):
        service, _, verb = action_name.partition(":")
        resource_type = action_name.split(":", 1)[0]
        services.setdefault(service, {"service": service, "actions": []})
        services[service]["actions"].append({
            "action": action_name,
            "verb": verb,
            "kind": "read" if verb in read_verbs else "mutate",
            # Whether a policy can name one instance or only the type. An operator writing
            # `resources` needs to know which of the two they are dealing with.
            "scope": "singleton" if resources.is_singleton(resource_type) else "instance",
            "routes": sorted(
                {f"{entry.method} {entry.endpoint}" for entry in entries}
            ),
        })

    actions = [a for s in services.values() for a in s["actions"]]
    return {
        "_comment": (
            "GENERATED by bin/gen-action-vocabulary.py from the live action registry. Do not edit. "
            "This is the source of truth for services and actions: a policy author, a test and the "
            "policy editor all read it instead of guessing action names."
        ),
        "counts": {
            "services": len(services),
            "actions": len(actions),
            "reads": sum(1 for a in actions if a["kind"] == "read"),
            "mutations": sum(1 for a in actions if a["kind"] == "mutate"),
        },
        "resource_types": sorted(resources.declared_types()),
        "services": [services[name] for name in sorted(services)],
    }


def render_markdown(data: dict) -> str:
    counts = data["counts"]
    lines = [
        "<!-- GENERATED by bin/gen-action-vocabulary.py. Do not edit. -->",
        "",
        "# Action vocabulary",
        "",
        "Every action the product declares, which is what a policy's `actions` field may name.",
        "**Generated from the live registry** — a route without a declaration cannot appear here,",
        "and the build gate in `backend/tests/test_action_coverage.py` fails if one exists.",
        "",
        f"{counts['actions']} actions across {counts['services']} services: "
        f"{counts['reads']} reads and {counts['mutations']} mutations.",
        "",
        "A read-only role is `[\"*:read\", \"*:list\"]` — the two read verbs — rather than an",
        "enumeration of the reads below.",
        "",
    ]
    for service in data["services"]:
        lines += [
            f"## `{service['service']}`",
            "",
            "| Action | Kind | Scope | Routes |",
            "|---|---|---|---|",
        ]
        for entry in service["actions"]:
            routes = "<br>".join(f"`{r}`" for r in entry["routes"])
            lines.append(
                f"| `{entry['action']}` | {entry['kind']} | {entry['scope']} | {routes} |"
            )
        lines.append("")
    return "\n".join(lines) + "\n"


def render_json(data: dict) -> str:
    return json.dumps(data, indent=2, sort_keys=False) + "\n"


def _diff(path: Path, generated: str) -> str:
    """A unified diff of the tracked file against what the registry now produces.

    `--check` used to report only *which* files were stale, so the CI gate shelled out to
    `git diff` to show the contributor which action had changed. That cost the job a `git` binary
    — which `python:3.12-slim` does not have — so it failed with `git: command not found` and then
    reported "a generated source of truth is stale", blaming the documents for a missing tool.
    Printing the diff here keeps what git was there for and needs nothing but the stdlib.
    """
    tracked = path.read_text(encoding="utf-8").splitlines() if path.exists() else []
    name = str(path.relative_to(REPO_ROOT))
    return "\n".join(difflib.unified_diff(
        tracked,
        generated.splitlines(),
        fromfile=f"{name} (tracked)",
        tofile=f"{name} (regenerated)",
        lineterm="",
    ))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero if either tracked file differs from what the registry would produce",
    )
    args = parser.parse_args()

    data = build()
    rendered = {JSON_OUT: render_json(data), MD_OUT: render_markdown(data)}

    if args.check:
        stale = [
            path for path, text in rendered.items()
            if not path.exists() or path.read_text(encoding="utf-8") != text
        ]
        if stale:
            for path in stale:
                print(_diff(path, rendered[path]), file=sys.stderr)
            print(
                "stale: "
                + ", ".join(str(p.relative_to(REPO_ROOT)) for p in stale)
                + "\nAn action was added, removed or renamed without regenerating."
                + "\nRun: bin/gen-action-vocabulary.py",
                file=sys.stderr,
            )
            return 1
        print("action vocabulary is current")
        return 0

    for path, text in rendered.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
