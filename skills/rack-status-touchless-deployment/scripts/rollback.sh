#!/usr/bin/env bash
# Restore the exact prior image/configuration and head-node script snapshot.
set -Eeuo pipefail
umask 077
SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
source "$SCRIPT_DIR/lib.sh"
NVIS_PHASE=rollback
nvis_load_env
state_dir=''
while [[ $# -gt 0 ]]; do
  case "$1" in --state-dir) state_dir=${2:?}; shift 2;; *) nvis_die "unknown argument: $1";; esac
done
[[ -n "$state_dir" ]] || state_dir="${NVIS_STATE_ROOT:-$NVIS_EVIDENCE_ROOT/state}/${NVIS_RELEASE_SHA256,,}"
nvis_safe_abs_path "$state_dir" && [[ -d "$state_dir" && ! -L "$state_dir" ]] || nvis_die 'unsafe or absent rollback state directory'
state="$state_dir/rollback.env"
[[ -f "$state" && ! -L "$state" ]] || nvis_die 'rollback record is absent'
[[ $(stat -c '%a' "$state") == 600 ]] || nvis_die 'rollback record permissions are not 0600'
# This file is generated by deploy.sh with printf %q, contains no secrets, and is never operator supplied.
source "$state"
for var in NVIS_NEW_CONTAINER; do [[ -n "${!var:-}" ]] || nvis_die "rollback record missing $var"; done

report="$state_dir/rollback-report.txt"; touch "$report"; chmod 600 "$report"
record() { printf '%s %s\n' "$(date -u +%FT%TZ)" "$*" | tee -a "$report"; }
record "rollback=start new_container=$NVIS_NEW_CONTAINER old_container_id=${NVIS_OLD_CONTAINER_ID:-none}"

# Restore scripts first. Remove only paths introduced by this release; preserve unrelated head-only files.
if [[ -f "$state_dir/remote-scripts-before.tar" ]]; then
  printf '%s  %s\n' "$(awk '{print $1}' "$state_dir/remote-scripts-before.tar.sha256")" "$state_dir/remote-scripts-before.tar" | sha256sum -c - >/dev/null || nvis_die 'remote script backup checksum mismatch'
  nvis_ssh_opts
  if [[ -f "$state_dir/scripts.manifest" && -f "$state_dir/remote-scripts-before.manifest" ]]; then
    comm -23 <(awk '{print $2}' "$state_dir/scripts.manifest" | LC_ALL=C sort) \
      <(awk '{print $2}' "$state_dir/remote-scripts-before.manifest" | LC_ALL=C sort) >"$state_dir/scripts-new-only.txt"
    while IFS= read -r rel; do
      [[ "$rel" =~ ^\./[A-Za-z0-9._/-]+$ ]] || nvis_die 'unsafe new-only script path in rollback record'
      ssh "${NVIS_SSH_OPTS[@]}" "$RACK_SSH_USER@$RACK_SSH_HOST" \
        "rm -f '$RACK_REMOTE_BASE_PATH/bin/scripts/${rel#./}'" </dev/null
    done <"$state_dir/scripts-new-only.txt"
  fi
  cat "$state_dir/remote-scripts-before.tar" | ssh "${NVIS_SSH_OPTS[@]}" "$RACK_SSH_USER@$RACK_SSH_HOST" \
    "set -eu; base='$RACK_REMOTE_BASE_PATH'; mkdir -p \"\$base\"; tar -C \"\$base\" -xf -"
  record 'rollback_scripts=restored'
elif [[ "${NVIS_REMOTE_SCRIPTS_EXISTED:-YES}" == NO && -f "$state_dir/scripts.manifest" ]]; then
  nvis_ssh_opts
  while IFS= read -r rel; do
    rel=${rel#*  }; [[ "$rel" =~ ^\./[A-Za-z0-9._/-]+$ ]] || nvis_die 'unsafe first-install script path'
    ssh "${NVIS_SSH_OPTS[@]}" "$RACK_SSH_USER@$RACK_SSH_HOST" "rm -f '$RACK_REMOTE_BASE_PATH/bin/scripts/${rel#./}'" </dev/null
  done <"$state_dir/scripts.manifest"
  record 'rollback_scripts=removed_initial_install_files'
fi

if [[ -n "${NVIS_OLD_RELEASE:-}" && -d "$NVIS_OLD_RELEASE" ]]; then
  [[ -f "$NVIS_OLD_STATE/compose.env" && -f "$NVIS_OLD_STATE/docker-compose.release.yml" ]] || nvis_die 'prior Compose rollback evidence absent'
  old_args=(-f "$NVIS_OLD_RELEASE/docker-compose.yml" -f "$NVIS_OLD_STATE/docker-compose.release.yml")
  if [[ -f "$NVIS_OLD_STATE/site-override.path" ]]; then
    old_site_override=$(<"$NVIS_OLD_STATE/site-override.path")
    [[ -f "$old_site_override" ]] || nvis_die 'prior site override disappeared'
    printf '%s  %s\n' "$(awk '{print $1}' "$NVIS_OLD_STATE/site-override.sha256")" "$old_site_override" | sha256sum -c - >/dev/null || nvis_die 'prior site override drifted'
    old_args+=(-f "$old_site_override")
  fi
  docker compose --project-name "$NVIS_COMPOSE_PROJECT" --project-directory "$NVIS_OLD_RELEASE" \
    --env-file "$NVIS_OLD_STATE/compose.env" "${old_args[@]}" up -d --no-build --force-recreate "$NVIS_COMPOSE_SERVICE"
  restored_image=$(docker inspect -f '{{.Config.Image}}' "$NVIS_NEW_CONTAINER")
  [[ "$restored_image" == "$NVIS_OLD_IMAGE" ]] || nvis_die "rollback image mismatch: $restored_image"
  record "old_release=recreated image=$restored_image"
  ln -s "$NVIS_OLD_RELEASE" "$NVIS_DEPLOY_PATH/.current.rollback.$$"
  mv -Tf "$NVIS_DEPLOY_PATH/.current.rollback.$$" "$NVIS_DEPLOY_PATH/current"
  record "active_release=$NVIS_OLD_RELEASE"
  "$SCRIPT_DIR/verify.sh" --release-root "$NVIS_OLD_RELEASE" >>"$report" 2>&1 || nvis_die "restored service failed verification; see $report"
else
  [[ -f "$NVIS_NEW_STATE/compose.env" && -f "$NVIS_NEW_STATE/docker-compose.release.yml" ]] || nvis_die 'new Compose evidence absent'
  new_args=(-f "$NVIS_NEW_RELEASE/docker-compose.yml" -f "$NVIS_NEW_STATE/docker-compose.release.yml")
  if [[ -f "$NVIS_NEW_STATE/site-override.path" ]]; then new_args+=(-f "$(<"$NVIS_NEW_STATE/site-override.path")"); fi
  docker compose --project-name "$NVIS_COMPOSE_PROJECT" --project-directory "$NVIS_NEW_RELEASE" \
    --env-file "$NVIS_NEW_STATE/compose.env" "${new_args[@]}" down
  record 'first_install_service=removed'
fi
rm -f "$state_dir/checkpoints/scripts.done" "$state_dir/checkpoints/deploy.done" "$state_dir/checkpoints/verify.done" "$state_dir/checkpoints/activate.done" "$state_dir/checkpoints/smoke.done"
record 'status=ROLLED_BACK'
printf 'ROLLED_BACK report=%s\n' "$report"
