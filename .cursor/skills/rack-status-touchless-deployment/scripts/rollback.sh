# Restore the exact prior container image and the head-node script snapshot taken before this
# deployment mutated anything. Invoked automatically by deploy.sh on a post-mutation failure, or
# by hand with --state-dir pointing at a run directory.
set -Eeuo pipefail
umask 077
SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
source "$SCRIPT_DIR/lib.sh"
# shellcheck disable=SC2034  # read by nvis_die() in lib.sh
NVIS_PHASE=rollback
nvis_load_env

state_dir=''
while [[ $# -gt 0 ]]; do
  case "$1" in --state-dir) state_dir=${2:?}; shift 2;; *) nvis_die "unknown argument: $1";; esac
done
[[ -n "$state_dir" ]] || state_dir="${NVIS_STATE_ROOT:-$NVIS_EVIDENCE_ROOT/state}/${NVIS_IMAGE_SHA256,,}"
nvis_safe_abs_path "$state_dir" && [[ -d "$state_dir" && ! -L "$state_dir" ]] || nvis_die 'unsafe or absent rollback state directory'
state="$state_dir/rollback.env"
[[ -f "$state" && ! -L "$state" ]] || nvis_die 'rollback record is absent'
[[ $(stat -c '%a' "$state") == 600 ]] || nvis_die 'rollback record permissions are not 0600'
# Generated by deploy.sh with printf %q; contains no secrets and is never operator-supplied.
# shellcheck disable=SC1090
source "$state"
[[ -n "${NVIS_CONTAINER:-}" ]] || nvis_die 'rollback record missing NVIS_CONTAINER'

report="$state_dir/rollback-report.txt"; touch "$report"; chmod 600 "$report"
record() { printf '%s %s\n' "$(date -u +%FT%TZ)" "$*" | tee -a "$report"; }
record "rollback=start container=$NVIS_CONTAINER prior_image=${NVIS_OLD_IMAGE_REF:-none}"

# 1. Restore the head-node scripts to the pre-deployment snapshot, if one was captured.
if [[ -f "$state_dir/remote-scripts-before.tar" ]]; then
  printf '%s  %s\n' "$(awk '{print $1}' "$state_dir/remote-scripts-before.tar.sha256")" "$state_dir/remote-scripts-before.tar" \
    | sha256sum -c - >/dev/null || nvis_die 'remote script backup checksum mismatch'
  nvis_ssh_opts
  # Remove only files this deployment newly introduced, then restore the prior tree over the top.
  if [[ -f "$state_dir/scripts.manifest" ]]; then
    local_before=$(mktemp)
    tar -tf "$state_dir/remote-scripts-before.tar" | sed 's#^bin/scripts/#./#' | LC_ALL=C sort >"$local_before"
    while IFS= read -r line; do
      rel=${line#*  }; [[ "$rel" =~ ^\./[A-Za-z0-9._/-]+$ ]] || continue
      grep -Fqx "$rel" "$local_before" && continue
      ssh "${NVIS_SSH_OPTS[@]}" "$RACK_SSH_USER@$RACK_SSH_HOST" \
        "rm -f '$RACK_REMOTE_BASE_PATH/bin/scripts/${rel#./}'" </dev/null
    done <"$state_dir/scripts.manifest"
    rm -f "$local_before"
  fi
  cat "$state_dir/remote-scripts-before.tar" | ssh "${NVIS_SSH_OPTS[@]}" "$RACK_SSH_USER@$RACK_SSH_HOST" \
    "set -eu; base='$RACK_REMOTE_BASE_PATH'; mkdir -p \"\$base\"; tar -C \"\$base\" -xf -"
  record 'rollback_scripts=restored'
elif [[ "${NVIS_REMOTE_SCRIPTS_EXISTED:-YES}" == NO && -f "$state_dir/scripts.manifest" ]]; then
  nvis_ssh_opts
  while IFS= read -r line; do
    rel=${line#*  }; [[ "$rel" =~ ^\./[A-Za-z0-9._/-]+$ ]] || nvis_die 'unsafe first-install script path'
    ssh "${NVIS_SSH_OPTS[@]}" "$RACK_SSH_USER@$RACK_SSH_HOST" "rm -f '$RACK_REMOTE_BASE_PATH/bin/scripts/${rel#./}'" </dev/null
  done <"$state_dir/scripts.manifest"
  record 'rollback_scripts=removed_initial_install_files'
fi

# 2. Recreate the container from the exact prior image, with the same bind mounts, or remove it on
#    a first install. The config/state directories are unchanged by a deploy, so the prior image on
#    the same mounts is a faithful restore.
docker rm -f "$NVIS_CONTAINER" >/dev/null 2>&1 || true
if [[ -n "${NVIS_OLD_IMAGE_REF:-}" ]]; then
  args=(run -d --name "$NVIS_CONTAINER" --restart unless-stopped
    -p "${NVIS_BIND_ADDR:-127.0.0.1}:${NVIS_WEB_PORT}:5000"
    -v "$NVIS_CONFIG_DIR:/app/config:ro"
    -v "$NVIS_STATE_DIR:/app/var"
    -v "$RACK_SSH_KEY_PATH:/run/secrets/ssh_key:ro"
    -e RACK_SSH_KEY=/run/secrets/ssh_key)
  [[ -n "${NVIS_CPUS:-}" ]]   && args+=(--cpus "$NVIS_CPUS")
  [[ -n "${NVIS_MEMORY:-}" ]] && args+=(--memory "$NVIS_MEMORY")
  [[ -n "${NVIS_CA_CERT_FILE:-}" ]] && args+=(-v "$NVIS_CA_CERT_FILE:$NVIS_CA_CERT_FILE:ro")
  args+=("$NVIS_OLD_IMAGE_REF")
  docker "${args[@]}"
  restored=$(docker inspect -f '{{.Config.Image}}' "$NVIS_CONTAINER")
  [[ "$restored" == "$NVIS_OLD_IMAGE_REF" ]] || nvis_die "rollback image mismatch: $restored"
  sleep 6
  nvis_health_ping || record 'warning: restored container did not answer /api/status yet'
  record "old_image=recreated image=$restored"
else
  record 'first_install_container=removed'
fi

rm -f "$state_dir/checkpoints/scripts.done" "$state_dir/checkpoints/deploy.done" \
      "$state_dir/checkpoints/verify.done" "$state_dir/checkpoints/activate.done" "$state_dir/checkpoints/smoke.done"
record 'status=ROLLED_BACK'
printf 'ROLLED_BACK report=%s\n' "$report"
